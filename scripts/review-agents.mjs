#!/usr/bin/env node
// Write the two reviewer agents from the briefs in references/review.md, so the subagents Claude Code and
// OpenCode spawn and the prompts other harnesses paste are the same text:
//   agents/*.md                      Claude Code plugin agents
//   integrations/opencode/agents/    OpenCode subagents (mode: subagent, file edits denied)
//   node scripts/review-agents.mjs           write both
//   node scripts/review-agents.mjs --check   fail when either differs from review.md
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REVIEW = path.join(ROOT, 'skills', 'frontend-craft', 'references', 'review.md');
const AGENTS = path.join(ROOT, 'agents');
const OPENCODE = path.join(ROOT, 'integrations', 'opencode', 'agents');

const SPECS = [
  {
    name: 'craft-design-critic',
    heading: 'Brief 1: design critic',
    description: 'Independent design critic for a page built with frontend-craft: judges colour, hero, type, composition and copy against the subject at 1440, 390 and 320 px, runs impeccable critique, audit and detect, and returns at most 12 findings with a ship verdict. Read-only. Use after the frontend-craft check passes, or when asked to review a built page.',
  },
  {
    name: 'craft-motion-auditor',
    heading: 'Brief 2: motion and mobile auditor',
    description: 'Independent motion and mobile auditor for a page built with frontend-craft: measures when each scroll-driven animation starts and ends, checks speed, pause controls, reduced motion and use at 390, 360 and 320 px, and reviews the motion code against Emil Kowalski\'s rules. Read-only. Use after the frontend-craft check passes, or when motion feels wrong.',
  },
];

/** The fenced brief under a heading of review.md. */
export function brief(text, heading) {
  const at = text.indexOf(`## ${heading}`);
  if (at < 0) throw new Error(`review.md has no "## ${heading}"`);
  const m = text.slice(at).match(/```\n([\s\S]*?)\n```/);
  if (!m) throw new Error(`no fenced brief under "${heading}"`);
  return m[1];
}

const FRONTMATTER = {
  claude: (s) => [`name: ${s.name}`, 'description: >-', `  ${s.description}`],
  // OpenCode v2: the file name is the agent id; a reviewer may run shell (playwright-cli, impeccable detect) but never edit.
  opencode: (s) => ['description: >-', `  ${s.description}`, 'mode: subagent', 'permissions:', '  - action: edit', '    resource: "*"', '    effect: deny'],
};

export function agentFiles(text = fs.readFileSync(REVIEW, 'utf8'), host = 'claude') {
  return Object.fromEntries(SPECS.map((s) => [`${s.name}.md`, [
    '---',
    ...FRONTMATTER[host](s),
    '---',
    '',
    '<!-- Generated by scripts/review-agents.mjs from skills/frontend-craft/references/review.md. Edit that file. -->',
    '',
    'The caller gives you the page URL, the project folder, the subject and `<skill>`, the installed frontend-craft folder (it holds scripts/check.mjs; its sibling skills sit next to it). If any is missing, find the project folder by its `.craft/` and the URL in `.craft/gate.json`.',
    '',
    brief(text, s.heading),
    '',
  ].join('\n')]));
}

if (process.argv[1] && fs.realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = fs.readFileSync(REVIEW, 'utf8');
  const targets = [[AGENTS, agentFiles(text, 'claude')], [OPENCODE, agentFiles(text, 'opencode')]];
  const rel = (dir, f) => path.relative(ROOT, path.join(dir, f));
  if (process.argv.includes('--check')) {
    const stale = targets.flatMap(([dir, files]) => Object.entries(files)
      .filter(([f, body]) => !fs.existsSync(path.join(dir, f)) || fs.readFileSync(path.join(dir, f), 'utf8') !== body).map(([f]) => rel(dir, f)));
    if (stale.length) { console.error(`agents out of date: ${stale.join(', ')} (run node scripts/review-agents.mjs)`); process.exit(1); }
    console.log('agents match review.md');
  } else {
    for (const [dir, files] of targets) {
      fs.mkdirSync(dir, { recursive: true });
      for (const [f, body] of Object.entries(files)) fs.writeFileSync(path.join(dir, f), body);
    }
    console.log(`wrote ${targets.flatMap(([dir, files]) => Object.keys(files).map((f) => rel(dir, f))).join(', ')}`);
  }
}
