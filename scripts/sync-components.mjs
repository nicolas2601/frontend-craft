#!/usr/bin/env node
/*
  Rebuild skills/frontend-craft/library/components.json from the curated list below and the React Bits
  registry (https://reactbits.dev/r/<Name>-TS-TW.json): description and npm dependencies come from the
  registry, never typed by hand. Run after editing the list:  node scripts/sync-components.mjs
*/
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CURATED } from './components-curated.mjs';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'skills/frontend-craft/library/components.json');
const registry = (name, variant) => `https://reactbits.dev/r/${name}-${variant}`;

async function meta(name) {
  const res = await fetch(registry(name, 'TS-TW'));
  if (!res.ok) throw new Error(`${name}: registry answered ${res.status}`);
  const j = await res.json();
  return { description: j.description ?? '', deps: (j.dependencies ?? []).map((d) => d.replace(/@[\^~]?\d.*$/, '')) };
}

const components = [];
for (const [name, job, fits, modes] of CURATED) {
  const m = await meta(name);
  components.push({ id: name, source: 'react-bits', job, fits, modes, description: m.description, deps: m.deps,
    add: { tsTailwind: registry(name, 'TS-TW'), tsCss: registry(name, 'TS-CSS'), jsCss: registry(name, 'JS-CSS') } });
}
const doc = {
  $comment: 'Generated by scripts/sync-components.mjs from React Bits (MIT + Commons Clause: free inside a site or app, not for resale as a component kit). start.mjs deals one component that fits the direction; references/components.md says how to add, adapt and verify it.',
  components,
};
fs.writeFileSync(OUT, `${JSON.stringify(doc, null, 2)}\n`);
console.log(`components.json: ${components.length} components`);
