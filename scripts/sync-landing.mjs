#!/usr/bin/env node
/*
  Rebuild skills/frontend-craft/library/landing-patterns.json from ui-ux-pro-max's landing.csv (MIT, bundled
  at skills/ui-ux-pro-max/data/landing.csv). The section order and the main-action placement come from the
  CSV, never typed by hand; which pattern serves which kind of page is the curated list below. The CSV's
  colour and effect columns are left out on purpose: they are the generic look frontend-craft refuses.

    node scripts/sync-landing.mjs           write the JSON
    node scripts/sync-landing.mjs --check   fail when the JSON differs from what the CSV gives
*/
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const CSV = path.join(ROOT, 'skills/ui-ux-pro-max/data/landing.csv');
const OUT = path.join(ROOT, 'skills/frontend-craft/library/landing-patterns.json');

/** Most specific first: the deal takes the first entry whose kinds hold the page's kind and whose moods (if any) meet the subject's. */
export const CURATED = [
  ['event-conference-landing', ['event'], []],
  ['portfolio-grid', ['portfolio'], []],
  ['faq-documentation-landing', ['docs'], []],
  ['product-demo-features', ['product'], []],
  ['feature-rich-showcase', ['landing', 'site'], ['tech', 'developer', 'finance', 'science', 'precise']],
  ['trust-authority-conversion', ['landing', 'site'], ['health', 'finance']],
  ['scroll-triggered-storytelling', ['brand', 'campaign'], []],
  ['hero-centric-design', ['landing', 'site', 'venue', 'brand', 'campaign'], []],
];

/** RFC 4180 rows: quoted fields may hold commas, doubled quotes and newlines. */
export function parseCsv(text) {
  const rows = [];
  let row = [], field = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; } else if (c === '"') quoted = false; else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n') { row.push(field); rows.push(row); row = []; field = ''; }
    else if (c !== '\r') field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows;
}

export function landingPatterns(csvText) {
  const [head, ...rows] = parseCsv(csvText);
  const col = (name) => {
    const i = head.indexOf(name);
    if (i < 0) throw new Error(`landing.csv has no "${name}" column`);
    return i;
  };
  const [ID, NAME, ORDER, CTA] = ['Pattern ID', 'Pattern Name', 'Section Order', 'Primary CTA Placement'].map(col);
  const byId = new Map(rows.filter((r) => r.length > ID).map((r) => [r[ID].trim(), r]));
  return CURATED.map(([id, kinds, moods]) => {
    const r = byId.get(id);
    if (!r) throw new Error(`landing.csv has no pattern "${id}"`);
    return { id, name: r[NAME].trim(), kinds, moods, order: r[ORDER].split('>').map((s) => s.trim()).filter(Boolean), cta: r[CTA].trim() };
  });
}

export function landingDoc(csvText = fs.readFileSync(CSV, 'utf8')) {
  return `${JSON.stringify({
    $comment: 'Generated by scripts/sync-landing.mjs from ui-ux-pro-max data/landing.csv (MIT, nextlevelbuilder/ui-ux-pro-max-skill). order and cta come from the CSV; kinds and moods say which pages each pattern serves. The brief prints the matched reading order next to the composition.',
    patterns: landingPatterns(csvText),
  }, null, 2)}\n`;
}

if (process.argv[1] && fs.realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const doc = landingDoc();
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8') !== doc) { console.error('landing-patterns.json is out of date (run node scripts/sync-landing.mjs)'); process.exit(1); }
    console.log('landing-patterns.json matches landing.csv');
  } else {
    fs.writeFileSync(OUT, doc);
    console.log(`landing-patterns.json: ${CURATED.length} patterns`);
  }
}
